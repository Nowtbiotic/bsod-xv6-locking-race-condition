int shared_counter = 0;
struct spinlock counter_lock;

int
sys_fork(void)
{
  return fork();
}

int
sys_exit(void)
{
  exit();
  return 0;  // not reached
}

int
sys_wait(void)
{
  return wait();
}

int
sys_kill(void)
{
  int pid;

  if(argint(0, &pid) < 0)
    return -1;
  return kill(pid);
}

int
sys_getpid(void)
{
  return myproc()->pid;
}

int
sys_sbrk(void)
{
  int addr;
  int n;

  if(argint(0, &n) < 0)
    return -1;
  addr = myproc()->sz;
  if(growproc(n) < 0)
    return -1;
  return addr;
}

int
sys_sleep(void)
{
  int n;
  uint ticks0;

  if(argint(0, &n) < 0)
    return -1;
  acquire(&tickslock);
  ticks0 = ticks;
  while(ticks - ticks0 < n){
    if(myproc()->killed){
      release(&tickslock);
      return -1;
    }
    sleep(&ticks, &tickslock);
  }
  release(&tickslock);
  return 0;
}

// return how many clock tick interrupts have occurred
// since start.
int
sys_uptime(void)
{
  uint xticks;

  acquire(&tickslock);
  xticks = ticks;
  release(&tickslock);
  return xticks;
}

int
sys_counter_reset(void)
{
  shared_counter = 0;
  return 0;
}

int
sys_counter_increment(void)
{
  int old;
  int new_value;
  volatile int delay;

  acquire(&counter_lock);

  // Read the shared value.
  old = shared_counter;

  // Deliberately widen the race window.
  for(delay = 0; delay < 100000; delay++)
    ;

  // Write the old value + 1.
  new_value = old + 1;
  shared_counter = new_value;

  release(&counter_lock);

  return new_value;
}

int
sys_counter_get(void)
{
  return shared_counter;
}
